package showroomz.domain.post.type;

/**
 * 신고 처리 상태.
 *
 * <p>{@link #PENDING}인 행의 수가 곧 운영자 대기열이다. 접수만 하고 상태를 두지 않으면 같은 신고를
 * 몇 번이고 다시 읽게 되고, 조치가 끝난 게시물의 신고가 대기열에 계속 남는다.
 *
 * <p>신고자에게는 이 값을 돌려주지 않는다 — 누가 신고했는지와 마찬가지로 처리 결과도 신고 대상에게
 * 추적 단서가 되면 안 된다. 신고자 화면은 "접수됐습니다" 하나로 끝난다.
 */
public enum PostReportStatus {

    /** 접수 — 운영자 대기열에 있다 */
    PENDING,

    /**
     * 조치로 이어짐.
     *
     * <p>운영자가 이 게시물을 노출 중지하면 대기 중이던 신고가 <b>전부</b> 이 값으로 넘어간다.
     * 신고 하나하나를 따로 닫게 하면 같은 게시물에 걸린 신고 스무 건을 스무 번 닫아야 한다.
     */
    ACCEPTED,

    /** 검토 후 조치하지 않음 — 규정 위반이 아니라고 판단한 경우다 */
    DISMISSED
}
