package showroomz.api.creator.contract.type;

/**
 * 고정 지급비 지급 상태(§27 설계서 4-4) — 「체결완료 = <b>지급 전</b>」을 못박는 자리다.
 * 체결을 입금으로 오해하면 분쟁이 된다(§27-5).
 *
 * <p>{@code fixed_fee_paid_at} 원시값은 스튜디오에 내리지 않는다. 이 상태 enum만 내린다.
 */
public enum CreatorFixedFeePaymentState {

    /** 체결완료 · 브랜드의 지급 기록 없음 — 화면은 「아직 지급되지 않았습니다」로 그린다. */
    NOT_YET,

    /**
     * 체결완료 · 브랜드가 [지급 완료 기록]을 누름.
     *
     * <p><b>{@code PAID}라고 이름 붙이지 않는다.</b> 이 값은 브랜드가 버튼을 누른 사실일 뿐
     * <b>입금 사실이 아니다</b> — 플랫폼은 지급을 확인하지 않는다(§25-5-4). {@code PAID}로 이름을
     * 붙이면 화면이 「지급 완료」로 그리고, 실제로 안 들어온 돈이 들어온 것으로 표시된다.
     * 그 상태에서 분쟁이 나면 화면이 브랜드 편에서 거짓말을 한 셈이 된다.
     */
    RECORDED_BY_BRAND,

    /** 종결 3종 — 계약이 성립하지 않아 <b>지급 없음</b>이다. */
    NONE
}
